#!/usr/bin/env python3
"""Extract the 15 Chinese STHupo header glyphs from ui/src/song_data.c into:
  - app/assets/blobs/headers_sthupo.bin ('SHD1' pack for AT24C256 0x2F id=5)
  - Guard ui/src/song_data.c with #ifndef AT32_SLIM_ROM so AT32 build links
    ONLY digits '0'..'9' (~1.8 KB Flash) while Host keeps the full table or
    also exercises SHD1 cleanly.
"""

import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SONG_C = os.path.join(ROOT, "ui", "src", "song_data.c")
OUT_BIN = os.path.join(ROOT, "app", "assets", "blobs", "headers_sthupo.bin")
OUT_H = os.path.join(ROOT, "host", "hdr_asset_test.h")


def crc16_ccitt(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if (crc & 0x8000) else ((crc << 1) & 0xFFFF)
    return crc


def main() -> None:
    with open(SONG_C, "r", encoding="utf-8") as f:
        src = f.read()

    m_cov = re.search(r"const uint8_t song_cover\[\]\s*=\s*\{(.*?)\};", src, re.S)
    m_gly = re.search(r"const song_glyph_t song_glyph\[\]\s*=\s*\{(.*?)\};", src, re.S)
    assert m_cov and m_gly

    cov_bytes = bytes(int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", m_cov.group(1)))
    entries = []
    for line in m_gly.group(1).splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        inner = line.strip("{}, ")
        parts = [p.strip() for p in inner.split(",")]
        if parts[0].startswith("'"):
            cp = ord(parts[0].strip("'"))
        else:
            cp = int(parts[0], 16)
        face, w, h, adv, x, y, off = [int(v, 0) for v in parts[1:8]]
        entries.append((cp, face, w, h, adv, x, y, off))

    # Split face==0 (15 CJK glyphs) vs face==1 (digits '0'..'9')
    hdr_entries = [e for e in entries if e[1] == 0]
    dig_entries = [e for e in entries if e[1] == 1]
    assert len(hdr_entries) == 15 and len(dig_entries) == 10
    split_off = dig_entries[0][7]
    assert all(e[7] < split_off for e in hdr_entries)
    assert all(e[7] >= split_off for e in dig_entries)

    # Pack BOTH face==0 (15 CJK headers) and face==1 (10 STHupo digits '0'..'9')
    # into headers_sthupo.bin ('SHD1'), leaving 0 B bitmap tables in AT32 Flash.
    all_entries = hdr_entries + dig_entries
    base_off = all_entries[0][7]
    all_cover = cov_bytes[base_off:]

    tbl = bytearray()
    for cp, face, w, h, adv, x, y, off in all_entries:
        tbl.extend(struct.pack("<HHBBBbbB", cp, off - base_off, w, h, adv, x, y, face))
    body = bytes(tbl) + all_cover
    hdr_sz = 12
    total = hdr_sz + len(body)
    crc = crc16_ccitt(body)
    blob = struct.pack("<IHHHH", 0x31444853, len(all_entries), hdr_sz + len(tbl), total, crc) + body

    os.makedirs(os.path.dirname(OUT_BIN), exist_ok=True)
    with open(OUT_BIN, "wb") as f:
        f.write(blob)

    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by host/gen_hdr_assets.py -- Host test fixture only */\n")
        f.write("#ifndef HDR_ASSET_TEST_H\n#define HDR_ASSET_TEST_H\n#include <stdint.h>\n\n")
        f.write(f"static const uint8_t headers_sthupo_blob[{len(blob)}] = {{\n")
        for i in range(0, len(blob), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in blob[i:i + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n#endif\n")

    # Empty on-chip table when AT32_SLIM_ROM: clock digits & headers stream from AT24C256 'SHD1',
    # with crisp vector/dot-font fallback before companion asset sync.
    slim_inc = os.path.join(ROOT, "ui", "src", "song_data_slim.inc")
    with open(slim_inc, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by host/gen_hdr_assets.py: zero-ROM slim stub (SHD1 in AT24C256) */\n")
        f.write("const int song_line_h[2] = {38, 47};\n")
        f.write("const uint8_t song_cover[] = { 0u };\n")
        f.write("const song_glyph_t song_glyph[] = { {0u, 0u, 0u, 0u, 0u, 0, 0, 0u} };\n")
        f.write("const int song_glyph_n = 0;\n")

    print(f"Generated SHD1 ({len(blob)} B, {len(all_entries)} glyphs) & zero-ROM song_data_slim.inc")


if __name__ == "__main__":
    main()
