#!/usr/bin/env python3
"""Compile ui/src/compass3d_mod.c into a zero-relocation ARM Cortex-M4 Thumb-2 PIC blob.

Outputs:
  - app/assets/blobs/compass3d_m4.bin (for Companion App 0x2F auto-sync into AT24C256)
  - host/compass3d_blob_test.h        (test fixture for host/render_test.c only)
"""

import os
import struct
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GCC_DIR = r"D:\dev\arm-none-eabi-gcc\bin"
GCC = os.path.join(GCC_DIR, "arm-none-eabi-gcc.exe")
OBJCOPY = os.path.join(GCC_DIR, "arm-none-eabi-objcopy.exe")
READELF = os.path.join(GCC_DIR, "arm-none-eabi-readelf.exe")
NM = os.path.join(GCC_DIR, "arm-none-eabi-nm.exe")

SRC = os.path.join(ROOT, "ui", "src", "compass3d_mod.c")
INC = os.path.join(ROOT, "ui")
OUT_BIN = os.path.join(ROOT, "app", "assets", "blobs", "compass3d_m4.bin")
OUT_H = os.path.join(ROOT, "host", "compass3d_blob_test.h")

LD_SCRIPT = """ENTRY(compass3d_entry)
SECTIONS
{
  . = 0x00000000;
  .blob : ALIGN(4)
  {
    *(.text.entry)
    *(.text*)
    *(.rodata*)
    . = ALIGN(4);
  }
  /DISCARD/ :
  {
    *(.ARM.exidx*)
    *(.ARM.extab*)
    *(.comment*)
    *(.note*)
    *(.ARM.attributes*)
  }
}
"""


def crc16_ccitt(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if (crc & 0x8000) else ((crc << 1) & 0xFFFF)
    return crc


def main() -> None:
    os.makedirs(os.path.dirname(OUT_BIN), exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "compass3d_mod.o")
        elf = os.path.join(tmp, "compass3d.elf")
        raw = os.path.join(tmp, "compass3d.bin")
        lds = os.path.join(tmp, "pic_blob.ld")
        with open(lds, "w", encoding="ascii") as f:
            f.write(LD_SCRIPT)

        subprocess.check_call([
            GCC,
            "-mcpu=cortex-m4",
            "-mthumb",
            "-Os",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-fpic",
            "-mpic-data-is-text-relative",
            "-ffreestanding",
            "-nostdlib",
            "-fno-common",
            "-fno-jump-tables",
            "-DCOMPASS3D_BLOB_ONLY=1",
            "-I" + INC,
            "-c",
            SRC,
            "-o",
            obj,
        ])
        subprocess.check_call([
            GCC,
            "-mcpu=cortex-m4",
            "-mthumb",
            "-nostdlib",
            "-Wl,--build-id=none",
            "-Wl,--gc-sections",
            "-T",
            lds,
            obj,
            "-o",
            elf,
        ])

        # Check symbols & sections for zero undefined refs, zero .got/.data/.bss
        nm_out = subprocess.check_output([NM, elf], text=True)
        entry_off = None
        for line in nm_out.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[0] == "U":
                raise RuntimeError(f"Unresolved external symbol in PIC blob: {line}")
            if len(parts) >= 3 and parts[2] == "compass3d_entry":
                entry_off = int(parts[0], 16)
        if entry_off is None:
            raise RuntimeError("compass3d_entry symbol missing in ELF")

        sec_out = subprocess.check_output([READELF, "-S", "-W", elf], text=True)
        for bad in (".got", ".data", ".bss", ".rel", ".rela"):
            if f" {bad}" in sec_out:
                raise RuntimeError(f"Unexpected section {bad} in PIC blob:\n{sec_out}")

        rel_out = subprocess.check_output([READELF, "-r", elf], text=True)
        if "There are no relocations" not in rel_out:
            raise RuntimeError(f"PIC blob contains relocations:\n{rel_out}")

        subprocess.check_call([OBJCOPY, "-O", "binary", "-j", ".blob", elf, raw])
        with open(raw, "rb") as f:
            payload = f.read()

    # Check if ARM Thumb bit already set in symbol address; header stores byte offset from blob start
    hdr_size = 12
    entry_byte_off = hdr_size + (entry_off & ~1)
    total_size = hdr_size + len(payload)
    crc = crc16_ccitt(payload)
    hdr = struct.pack("<IHHHH", 0x31443343, (1 << 8) | 1, entry_byte_off, total_size, crc)
    blob = hdr + payload

    with open(OUT_BIN, "wb") as f:
        f.write(blob)

    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by host/pack_compass3d.py -- Host test fixture only */\n")
        f.write("#ifndef COMPASS3D_BLOB_TEST_H\n#define COMPASS3D_BLOB_TEST_H\n#include <stdint.h>\n\n")
        f.write(f"static const uint8_t compass3d_m4_blob[{len(blob)}] = {{\n")
        for i in range(0, len(blob), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in blob[i:i + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n#endif\n")

    print(
        f"Packed C3D1 ARM Thumb-2 PIC blob: payload={len(payload)} B, "
        f"total={len(blob)} B, entry_off=0x{entry_byte_off:X}, crc16=0x{crc:04X}"
    )


if __name__ == "__main__":
    main()
