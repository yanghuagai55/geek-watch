#!/usr/bin/env python3
"""Compile cold PIC applets (ui/src/sport_mod.c -> SPR1, ui/src/analog_mod.c -> ANL1)
into zero-relocation ARM Cortex-M4 Thumb-2 blobs for AT24C256 dynamic swap.
"""

import os
import struct
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GCC_DIR = r"D:\dev\arm-none-eabi-gcc\bin"
GCC = os.path.join(GCC_DIR, "arm-none-eabi-gcc.exe")
OBJCOPY = os.path.join(GCC_DIR, "arm-none-eabi-objcopy.exe")
READELF = os.path.join(GCC_DIR, "arm-none-eabi-readelf.exe")
NM = os.path.join(GCC_DIR, "arm-none-eabi-nm.exe")
INC = os.path.join(ROOT, "ui")

def ld_for(entry_sym: str) -> str:
    return f"""ENTRY({entry_sym})
SECTIONS
{{
  . = 0x00000000;
  .blob : ALIGN(4)
  {{
    *(.text.entry)
    *(.text*)
    *(.rodata*)
    . = ALIGN(4);
  }}
  /DISCARD/ :
  {{
    *(.ARM.exidx*)
    *(.ARM.extab*)
    *(.comment*)
    *(.note*)
    *(.ARM.attributes*)
  }}
}}
"""


def crc16_ccitt(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if (crc & 0x8000) else ((crc << 1) & 0xFFFF)
    return crc


def build_pic(src_name: str, entry_sym: str, magic: int, out_bin_name: str) -> bytes:
    src = os.path.join(ROOT, "ui", "src", src_name)
    out_bin = os.path.join(ROOT, "app", "assets", "blobs", out_bin_name)
    os.makedirs(os.path.dirname(out_bin), exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "mod.o")
        elf = os.path.join(tmp, "mod.elf")
        raw = os.path.join(tmp, "mod.bin")
        lds = os.path.join(tmp, "pic.ld")
        with open(lds, "w", encoding="ascii") as f:
            f.write(ld_for(entry_sym))

        subprocess.check_call([
            GCC, "-mcpu=cortex-m4", "-mthumb", "-Os", "-Wall", "-Wextra", "-Werror",
            "-fpic", "-mpic-data-is-text-relative", "-ffreestanding", "-nostdlib",
            "-fno-common", "-fno-jump-tables", "-I" + INC, "-c", src, "-o", obj,
        ])
        subprocess.check_call([
            GCC, "-mcpu=cortex-m4", "-mthumb", "-nostdlib",
            "-Wl,--build-id=none", "-Wl,--gc-sections", "-T", lds, obj, "-o", elf,
        ])

        nm_out = subprocess.check_output([NM, elf], text=True)
        entry_off = None
        for line in nm_out.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[0] == "U":
                raise RuntimeError(f"{src_name}: unresolved external symbol: {line}")
            if len(parts) >= 3 and parts[2] == entry_sym:
                entry_off = int(parts[0], 16)
        assert entry_off is not None, f"{entry_sym} missing"

        sec_out = subprocess.check_output([READELF, "-S", "-W", elf], text=True)
        for bad in (".got", ".data", ".bss", ".rel", ".rela"):
            if f" {bad}" in sec_out:
                raise RuntimeError(f"{src_name}: bad section {bad}:\n{sec_out}")

        rel_out = subprocess.check_output([READELF, "-r", elf], text=True)
        if "There are no relocations" not in rel_out:
            raise RuntimeError(f"{src_name}: relocations present:\n{rel_out}")

        subprocess.check_call([OBJCOPY, "-O", "binary", "-j", ".blob", elf, raw])
        with open(raw, "rb") as f:
            payload = f.read()

    hdr_size = 12
    entry_byte_off = hdr_size + (entry_off & ~1)
    total_size = hdr_size + len(payload)
    crc = crc16_ccitt(payload)
    hdr = struct.pack("<IHHHH", magic, (1 << 8) | 1, entry_byte_off, total_size, crc)
    blob = hdr + payload
    with open(out_bin, "wb") as f:
        f.write(blob)
    print(f"Packed {src_name} -> {out_bin_name}: total={total_size} B, entry=0x{entry_byte_off:X}, crc=0x{crc:04X}")
    return blob


def main() -> None:
    sport_blob = build_pic("sport_mod.c", "sport_mod_entry", 0x31525053, "sport_mod_m4.bin")
    analog_blob = build_pic("analog_mod.c", "analog_mod_entry", 0x314C4E41, "analog_mod_m4.bin")
    sys_blob = build_pic("sys_mod.c", "sys_mod_entry", 0x31535953, "sys_mod_m4.bin")
    music_blob = build_pic("music_mod.c", "music_mod_entry", 0x3153554D, "music_mod_m4.bin")

    out_h = os.path.join(ROOT, "host", "pic_mods_test.h")
    with open(out_h, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by host/pack_pic_mods.py -- Host test fixture only */\n")
        f.write("#ifndef PIC_MODS_TEST_H\n#define PIC_MODS_TEST_H\n#include <stdint.h>\n\n")
        for name, blob in [
            ("sport_mod_m4_blob", sport_blob),
            ("analog_mod_m4_blob", analog_blob),
            ("sys_mod_m4_blob", sys_blob),
            ("music_mod_m4_blob", music_blob),
        ]:
            f.write(f"static const uint8_t {name}[{len(blob)}] = {{\n")
            for i in range(0, len(blob), 16):
                chunk = ", ".join(f"0x{b:02X}" for b in blob[i:i + 16])
                f.write(f"    {chunk},\n")
            f.write("};\n\n")
        f.write("#endif\n")


if __name__ == "__main__":
    main()
