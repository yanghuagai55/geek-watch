const ui_glyph_t *ui_font_find(uint32_t cp) {
    int lo = 0;
    int hi = (int)(sizeof glyphs / sizeof glyphs[0]) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        if (glyphs[mid].cp == cp) return &glyphs[mid];
        if (glyphs[mid].cp < cp) lo = mid + 1;
        else hi = mid - 1;
    }
    return 0;
}
